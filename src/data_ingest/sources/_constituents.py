"""The index constituent lists, shared by the sources that need a universe.

Leading underscore so the registry's auto-discovery skips this module. The
lists are committed files (data/constituents/*.csv, and for the S&P 500
data/sp500_membership.csv), regenerated by scripts/refresh_index_constituents.py
and scripts/refresh_sp500_membership.py — see those scripts for where they
come from and why they are not scraped at every run.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date, timedelta
from typing import List, Optional

import pandas as pd

from ..config import DATA_DIR

CONSTITUENTS_DIR = DATA_DIR / "constituents"

#: market id -> (display name, file). SP500 is not here: its members come
#: from the membership history (`sp500_members`) and its prices from
#: sp500-prices.
MARKETS = {
    "CAC40": ("CAC 40", "cac40.csv"),
    "DAX": ("DAX", "dax.csv"),
    "FTSE100": ("FTSE 100", "ftse100.csv"),
    "NIKKEI225": ("Nikkei 225", "nikkei225.csv"),
}

#: Quote units Yahoo uses that are a fraction of the ISO currency: London
#: lines quote in pence (GBp). Prices are stored in the ISO currency.
SUBUNITS = {"GBp": ("GBP", 100.0), "GBX": ("GBP", 100.0), "ZAc": ("ZAR", 100.0), "ILA": ("ILS", 100.0)}


@dataclass(frozen=True)
class Member:
    market: str
    ticker: str
    name: str
    kind: str  # "index" | "equity"
    quote_currency: str  # as Yahoo quotes it, e.g. "GBp"
    as_of: str

    @property
    def currency(self) -> str:
        """The ISO currency prices are stored in."""
        return SUBUNITS.get(self.quote_currency, (self.quote_currency, 1.0))[0]

    @property
    def divisor(self) -> float:
        return SUBUNITS.get(self.quote_currency, (self.quote_currency, 1.0))[1]


def members(market: str) -> List[Member]:
    path = CONSTITUENTS_DIR / MARKETS[market][1]
    frame = pd.read_csv(path, dtype=str, keep_default_na=False)
    return [
        Member(market, r.ticker, r.name, r.kind, r.quote_currency, r.as_of)
        for r in frame.itertuples(index=False)
    ]


def all_members() -> List[Member]:
    return [m for market in MARKETS for m in members(market)]


# ───────────────────────────────────────────────────────────── S&P 500 ──────

SP500_MEMBERSHIP_FILE = DATA_DIR / "sp500_membership.csv"

#: A company that leaves the index keeps being priced this long: a position
#: opened while it was a member still has to be marked, and its history is
#: what a backtest needs most. Longer than that, a symbol is too likely to
#: have gone or to belong to someone else.
SP500_KEPT_DAYS = 730


def sp500_members() -> List[str]:
    """Today's members of the S&P 500, sorted, as Yahoo writes them (BRK-B)."""
    stays = pd.read_csv(SP500_MEMBERSHIP_FILE, dtype=str, keep_default_na=False)
    return sorted(stays.loc[stays["date_removed"] == "", "ticker"])


def sp500_priced(today: Optional[date] = None) -> List[str]:
    """Today's members and those that left within SP500_KEPT_DAYS.

    A symbol that left because it was renamed or acquired is in there too and
    no longer exists on Yahoo: it fails to download, which is logged and
    costs nothing else.
    """
    since = ((today or date.today()) - timedelta(days=SP500_KEPT_DAYS)).isoformat()
    stays = pd.read_csv(SP500_MEMBERSHIP_FILE, dtype=str, keep_default_na=False)
    kept = (stays["date_removed"] == "") | (stays["date_removed"] >= since)
    return sorted(set(stays.loc[kept, "ticker"]))
