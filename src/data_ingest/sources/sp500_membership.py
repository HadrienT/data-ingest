"""Who was in the S&P 500, and when: one row per stay of a ticker in the index.

`equity-universe` knows today's members only, and a backtest run on them has
a survivorship bias: it leaves out what went bankrupt or was dropped for
having fallen, and holds in 2005 what only entered in 2015 for having risen.
The universe a strategy may pick from on day `d` is the membership on `d`:

    SELECT ticker FROM prices.sp500_membership
    WHERE as_of = (SELECT MAX(as_of) FROM prices.sp500_membership)
      AND date_added <= :d AND (date_removed IS NULL OR date_removed > :d)

- **`date_added`** is the first day in the index, **`date_removed`** the first
  day out of it (NULL for a current member). A ticker that left and came back
  has two rows.
- **The history starts on 1996-01-02.** A `date_added` of that day means
  "already a member", not "added that day", and the table says nothing of
  earlier dates.
- **A ticker is the symbol of the time.** A change of symbol closes a stay
  and opens another the same day (FB until 2022-06-09, META from then on),
  and a symbol can have belonged to two companies. Yahoo files a company's
  whole price history under today's symbol. One exception: a company that
  went bankrupt is under the symbol it took once delisted (LEHMQ for Lehman,
  ENRNQ for Enron, MTLQQ for the General Motors of before 2009).
- **Prices of delisted members are not in `prices.raw_daily`** (see
  `_equity_raw_common`): of the tickers that left the index, Yahoo still
  serves those that kept trading under the same symbol. Restricting the
  universe by date removes the look-ahead of "today's members"; it does not
  bring the dead back, and the bias is reduced, not removed.

The file is committed and regenerated by scripts/refresh_sp500_membership.py,
which names its sources. Rows are upserted on (ticker, date_added): a stay
whose start is corrected by a later refresh leaves its old row behind, with
an older `as_of`, hence the filter above.
"""

from __future__ import annotations

import pandas as pd

from ._constituents import SP500_MEMBERSHIP_FILE as MEMBERSHIP_FILE
from ..core.source import Source, Window
from ..core.spec import Column, TableSpec, WriteMode


def load() -> pd.DataFrame:
    frame = pd.read_csv(MEMBERSHIP_FILE, dtype=str, keep_default_na=False)
    for column in ("date_added", "date_removed", "as_of"):
        dates = pd.to_datetime(frame[column].where(frame[column] != "", None))
        frame[column] = dates.dt.date.astype(object).where(dates.notna(), None)
    return frame


def members_on(frame: pd.DataFrame, day) -> set:
    """The tickers in the index on `day` (a date)."""
    inside = (frame["date_added"] <= day) & frame["date_removed"].map(lambda d: d is None or d > day)
    return set(frame.loc[inside, "ticker"])


class SP500Membership(Source):
    name = "sp500-membership"
    description = "S&P 500 membership history since 1996: one row per stay of a ticker in the index"
    write_mode = WriteMode.UPSERT
    # The file only changes through a commit; a weekly run re-asserts it.
    schedule = "10 6 * * 1"
    lookback_days = 0

    table = TableSpec(
        schema="prices",
        name="sp500_membership",
        columns=(
            Column("ticker", "TEXT", nullable=False),
            Column("date_added", "DATE", nullable=False),
            Column("date_removed", "DATE"),
            Column("as_of", "DATE", nullable=False),
        ),
        primary_key=("ticker", "date_added"),
        indexes=(("date_added",),),
    )

    def fetch(self, window: Window) -> pd.DataFrame:
        return load()
